CREATE TABLE LEAGUE_RECORD
(
    LEAGUE_ID    INT          NOT NULL,
    PLAYER_ID    INT,
    RECORD_TITLE VARCHAR(100) NOT NULL,
    RECORD_VALUE SMALLINT DEFAULT 0,
    SEASON       TINYINT      NOT NULL,
    PRIMARY KEY (PLAYER_ID, LEAGUE_ID, SEASON, RECORD_TITLE),
    FOREIGN KEY (PLAYER_ID) REFERENCES PLAYER (PLAYER_ID),
    FOREIGN KEY (LEAGUE_ID, SEASON) REFERENCES LEAGUE_SEASON (LEAGUE_ID, SEASON)
);

CREATE TABLE LEAGUE_STANDINGS
(
    LEAGUE_ID INT     NOT NULL,
    TEAM_ID   INT     NOT NULL,
    SEASON    TINYINT NOT NULL,
    WINS      TINYINT DEFAULT 0,
    LOSSES    TINYINT DEFAULT 0,
    PRIMARY KEY (LEAGUE_ID, SEASON, TEAM_ID),
    FOREIGN KEY (TEAM_ID) REFERENCES TEAM (TEAM_ID),
    FOREIGN KEY (LEAGUE_ID, SEASON) REFERENCES LEAGUE_SEASON (LEAGUE_ID, SEASON)
);

